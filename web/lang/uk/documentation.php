    <h2>Огляд платформи</h2>
    <p>Ця платформа надає два інтегрованих модулі для управління станом безпеки вашої організації:</p>
    <ul>
        <li><strong>TPRM (Third Party Risk Management)</strong> &mdash; Відстежуйте, оцінюйте та виставляйте оцінки своїм постачальникам і підрядникам. Розумійте ризик безпеки, який кожен постачальник несе для вашої організації.</li>
        <li><strong>GRC (Governance, Risk &amp; Compliance)</strong> &mdash; Управляйте фреймворками відповідності (SOC 2, ISO 27001, PCI DSS, NIST CSF, CMMC, HIPAA, CIS Controls та іншими), відповідайте на єдине уніфіковане запитання, що охоплює всі фреймворки одночасно, відстежуйте внутрішні засоби контролю, завантажуйте докази, управляйте політиками та проводьте аудити.</li>
    </ul>
    <p>Адміністратори також мають доступ до <strong>Адміністративного порталу</strong> для конфігурації системи, управління користувачами, інтеграцій та обслуговування.</p>

