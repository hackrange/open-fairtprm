    </figure>
    <div class="callout callout-info">
        <strong>Якщо блокування вимкнено,</strong> заборона додатка лише позначає його як несанкціонований на платформі; нічого не надсилається до Zscaler. Ви побачите: <em>«Marked unsanctioned. Zscaler integration is not enabled; domain not added to URL Category.»</em>
    </div>
