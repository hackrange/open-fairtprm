<div class="doc-section" id="tprm-overview">
    <h2>Модуль TPRM: що таке Third Party Risk Management?</h2>
    <p>Кожна компанія покладається на зовнішніх постачальників &mdash; хмарні провайдери, компанії з нарахування зарплати, маркетингові платформи, ІТ-консультанти. Кожен постачальник може мати доступ до ваших даних або систем. <strong>TPRM</strong> допомагає відповісти на питання: «Наскільки ризикований кожен постачальник і чи захищають вони наші дані?»</p>
    <ul>
        <li>Додавайте та відстежуйте всіх постачальників в одному місці</li>
        <li>Присвоюйте рівень ризику (Tier 1 = найвищий ризик, Tier 3 = найнижчий)</li>
        <li>Надсилайте постачальникам опитувальники безпеки (оцінювання)</li>
        <li>Автоматично оцінюйте постачальників за допомогою зовнішніх сервісів оцінювання безпеки</li>
        <li>Виконуйте кількісний аналіз ризиків (FAIR) для оцінювання потенційних фінансових втрат</li>
        <li>Відстежуйте ризики четвертих сторін (постачальники ваших постачальників)</li>
        <li>Виявляйте некеровані SaaS-додатки (Shadow SaaS)</li>
    </ul>
