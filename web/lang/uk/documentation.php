<div class="doc-section" id="grc-step1">
    <h2>Крок 1: Створення першого оцінювання</h2>
    <p><strong>Оцінювання</strong> &mdash; це перевірення відповідності вашої організації. Воно являє собою оцінку на певний момент часу, де ви відповідаєте на питання безпеки, записуєте рейтинги зрілості та збираєте докази. Думайте про це як про «знімок відповідності».</p>

    <h3>Як створити нове оцінювання</h3>
    <ol class="steps">
        <li>На лівій бічній панелі натисніть <span class="menu-label">GRC Module</span>, щоб розгорнути його.</li>
        <li>Натисніть розділ <span class="menu-label">Assessment &amp; Audit</span>, щоб розгорнути його.</li>
        <li>Натисніть <span class="menu-label">Assessment Questionnaire</span>. Це відкриває головну сторінку оцінювання.</li>
        <li>У верхній частині сторінки ви побачите кнопку <span class="btn-label">+ New Assessment</span>. Натисніть її.</li>
        <li>З'явиться форма. Заповніть такі поля:
            <ul>
                <li><span class="field-label">Title</span> &mdash; Дайте оцінюванню описову назву. Наприклад: <code>2026 Annual Security Assessment - ACME Corp</code></li>
                <li><span class="field-label">Assessment Type</span> &mdash; Оберіть тип оцінювання:
                    <ul>
                        <li><strong>Initial</strong> &mdash; Ваше перше оцінювання (рекомендовано для нових користувачів)</li>
                        <li><strong>Periodic</strong> &mdash; Регулярне повторюване оцінювання (наприклад, щорічний огляд)</li>
                        <li><strong>Targeted</strong> &mdash; Цільове оцінювання конкретної сфери</li>
                        <li><strong>Pre-Audit</strong> &mdash; Підготовка перед формальним аудитом</li>
                        <li><strong>Certification</strong> &mdash; Оцінювання для цілей сертифікації (наприклад, SOC 2 Type II)</li>
                    </ul>
                </li>
                <li><span class="field-label">Scope</span> &mdash; Оберіть або опишіть організаційний обсяг. Це визначає, яка частина вашої організації оцінюється (наприклад, «Всі ІТ-системи» або «Хмарна інфраструктура»).</li>
                <li><span class="field-label">Lead Auditor</span> &mdash; Оберіть особу, яка керує цим оцінюванням. У спадному списку відображаються лише користувачі груп Administrator або Cyber GRC.</li>
                <li><span class="field-label">Planned Start Date</span> &mdash; Коли ви плануєте розпочати оцінювання.</li>
                <li><span class="field-label">Planned End Date</span> &mdash; Ваша цільова дата завершення.</li>
            </ul>
