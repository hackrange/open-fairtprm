<div class="doc-section" id="shadow-saas-grip">
    <h2>Інтеграція Grip Shadow SaaS <span class="new-badge">Нове у 2.6.2</span></h2>
    <p>«Shadow SaaS» означає хмарні додатки, які використовують співробітники, але які ніколи не були офіційно схвалені. <strong>Grip Security</strong> — це сервіс, що виявляє такі додатки. У v2.6.2 ви можете підключити свій обліковий запис Grip, щоб платформа автоматично завантажувала додатки, які знаходить Grip &mdash; разом із кількістю користувачів кожного, оцінкою ризику та сповіщеннями безпеки &mdash; і відображала їх на сторінці <a href="#tprm-shadow-saas">Shadow SaaS</a>.</p>
    <p>Налаштовується адміністратором у <span class="menu-label">Admin</span> &rarr; <span class="menu-label">Shadow SaaS</span> на вкладці <strong>Grip</strong>. Grip — один із двох провайдерів Shadow SaaS (інший — <a href="#shadow-saas-hero">Hero</a>); одночасно може бути увімкнено лише одного.</p>

    <h3>Підключення Grip (покрокова інструкція)</h3>
    <ol class="steps">
        <li>У Grip створіть <strong>API-токен</strong> та запишіть базову URL-адресу вашого тенанту (вона закінчується на <code>/public/saas</code>, наприклад <code>https://tenant.dep.grip.security/public/saas</code>).</li>
        <li>На платформі перейдіть до <span class="menu-label">Admin</span> &rarr; <span class="menu-label">Shadow SaaS</span> та знайдіть картку <strong>Grip Security Connection</strong>.</li>
        <li>Встановіть прапорець <span class="field-label">Enable Grip Security integration</span>.</li>
        <li>Вставте URL-адресу вашого тенанту у <span class="field-label">Server (Tenant Base URL)</span> та токен у <span class="field-label">API Token</span>.</li>
        <li>Натисніть <span class="btn-label">Save Configuration</span>, потім натисніть <span class="btn-label">Test Connection</span> для підтвердження. Повідомлення про успіх виглядає так: <em>«Connected to Grip — sample returned 1 record(s)»</em>.</li>
    </ol>
    <figure class="doc-figure">
        <img src="app/docs/grip-card.png" alt="Grip Security Connection settings" loading="lazy">
        <figcaption><strong>Admin &rarr; Shadow SaaS &rarr; Grip Security Connection.</strong> Введіть URL-адресу тенанту та API-токен, збережіть, потім перевірте.</figcaption>
    </figure>

    <h3>Автоматичне підтримання актуальності</h3>
    <p>Використовуйте загальну картку <strong>Scheduled Rehydration</strong> (нижче вкладок провайдера), щоб оновлювати дані увімкненого провайдера за розкладом. Встановіть прапорець <span class="field-label">Enable scheduled rehydration</span> та введіть <span class="field-label">Schedule (cron expression)</span> &mdash; наприклад <code>0 2 * * *</code> для щоденного запуску о 2:00 ночі; картка показує зрозуміле пояснення того, що ви ввели. Завдання автоматично встановлюється у системний планувальник (без ручних дій на сервері) та зберігається після перезапуску. Ви також можете натиснути <span class="btn-label">Run Now</span>, щоб негайно оновити дані. Той самий розклад обслуговує будь-якого увімкненого провайдера (Grip або Hero).</p>

    <h3>Що ви побачите після підключення</h3>
    <p>Виявлені додатки з'являються на сторінці <span class="menu-label">Shadow SaaS</span> як записи зі статусом <strong>Pending</strong> із оцінкою ризику (відображається за шкалою 1&ndash;5), категорією та кількістю користувачів. Звідти ви можете <strong>Allow</strong> (дозволити) додаток (що розпочне введення його як постачальника), <strong>Deny</strong> (заборонити) його (позначити як несанкціонований та за бажанням заблокувати в Zscaler) або <strong>Dismiss</strong> (відхилити) його.</p>
    <figure class="doc-figure">
        <img src="app/docs/shadow-saas.png" alt="Shadow SaaS list page" loading="lazy">
        <figcaption><strong>Сторінка Shadow SaaS.</strong> Виявлені та імпортовані додатки з їх ризиком та діями. Додатки, введені як постачальники, пропускаються при наступних синхронізаціях, а всі відхилені залишаються відхиленими.</figcaption>
    </figure>
</div>

<div class="doc-section" id="shadow-saas-hero">
    <h2>Інтеграція Hero Shadow SaaS <span class="new-badge">Нове у 2.6.2</span></h2>
    <p><strong>HERO Security</strong> — альтернативний провайдер Shadow SaaS. Замість Grip ви можете підключити обліковий запис HERO, і платформа завантажить постачальників, яких виявляє HERO &mdash; із їх статусом, оцінкою ризику, найактивнішим контактом та кількістю користувачів &mdash; до того самого списку <a href="#tprm-shadow-saas">Shadow SaaS</a>. Grip та Hero <strong>взаємно виключають одне одного</strong>: увімкнення Hero автоматично вимикає Grip (і навпаки), тому список завжди заповнюється рівно одним провайдером.</p>
    <p>Налаштовується адміністратором у <span class="menu-label">Admin</span> &rarr; <span class="menu-label">Shadow SaaS</span> на вкладці <strong>Hero</strong>.</p>

    <h3>Підключення Hero (покрокова інструкція)</h3>
    <ol class="steps">
        <li>На панелі адміністратора HERO створіть <strong>API-клієнт</strong> та скопіюйте його <strong>Client ID</strong> та <strong>Client Secret</strong> (секрет відображається лише один раз).</li>
        <li>На платформі перейдіть до <span class="menu-label">Admin</span> &rarr; <span class="menu-label">Shadow SaaS</span> та відкрийте вкладку <strong>Hero</strong>, щоб знайти картку <strong>HERO Security Connection</strong>.</li>
        <li>Встановіть прапорець <span class="field-label">Enable HERO Security integration</span> (це вимикає Grip).</li>
        <li>Залиште <span class="field-label">Server (Base URL)</span> як <code>https://api.herosecurity.ai/stable</code>, якщо не вказано інше, та вставте свої <span class="field-label">Client ID</span> та <span class="field-label">Client Secret</span>.</li>
        <li>Натисніть <span class="btn-label">Save Configuration</span>, потім <span class="btn-label">Test Connection</span>. Повідомлення про успіх виглядає так: <em>«Connected to HERO — sample returned 1 record(s)»</em>.</li>
    </ol>

    <h3>Що ви побачите після підключення</h3>
    <p>Постачальники HERO з'являються на сторінці <span class="menu-label">Shadow SaaS</span> так само, як додатки Grip &mdash; як записи зі статусом <strong>Pending</strong>, які можна Allow, Deny або Dismiss. Для кожного постачальника платформа записує:</p>
    <ul>
        <li><strong>Risk Score (1&ndash;5)</strong> &mdash; виводиться з найсерйознішої відкритої проблеми безпеки HERO для цього постачальника (critical&nbsp;=&nbsp;5 до low&nbsp;=&nbsp;2; постачальники без відкритих проблем залишаються без оцінки). Це та сама шкала 1&ndash;5, що використовує Grip.</li>
        <li><strong>Relationship Manager</strong> &mdash; найактивніший спостережуваний контакт постачальника (користувач із найвищою активністю електронної пошти).</li>
        <li><strong>Number of Users</strong> &mdash; скільки користувачів спостерігалося у взаємодії з постачальником.</li>
        <li><strong>Risk Type</strong> &mdash; зведення сигналів взаємодії HERO (авторизація, активність, комерційна взаємодія) та кількість відкритих проблем.</li>
    </ul>
    <p>Деякі стовпці, які надають інші джерела (категорія додатка, підтримка MFA, історія порушень, обсяги трафіку, обмін файлами), не є частиною API HERO, тому вони залишаються порожніми для рядків Hero.</p>

    <div class="callout callout-info">
        <strong>Зверніть увагу на час синхронізації.</strong> HERO повертає дані по одному постачальнику та обмежує запити за частотою, тому повне оновлення великого тенанту виконується кілька хвилин у фоновому режимі. Заплановане завдання та «Run Now» обидва автоматично регулюють темп, щоб залишатися в межах обмежень HERO.
    </div>
</div>

<div class="doc-section" id="zscaler">
    <h2>Інтеграція блокування Zscaler <span class="new-badge">Нове у 2.6.2</span></h2>
    <p><strong>Zscaler</strong> — це сервіс веб-безпеки, що може блокувати доступ до веб-сайтів. З цією інтеграцією, коли ви <strong>Deny</strong> (забороняєте) несанкціонований додаток на сторінці Shadow SaaS, платформа може автоматично додати веб-домен цього додатка до списку блокування у вашому обліковому записі Zscaler &mdash; щоб люди більше не могли до нього дістатися. Натискання <strong>Allow</strong> пізніше знімає блокування.</p>
    <p>Налаштовується адміністратором у <span class="menu-label">Admin</span> &rarr; <span class="menu-label">Shadow SaaS</span>, на картці <strong>Zscaler Connection</strong>.</p>

    <h3>Підключення Zscaler (покрокова інструкція)</h3>
    <ol class="steps">
        <li>У Zscaler (ZIdentity) створіть <strong>API-клієнт</strong> та скопіюйте його <strong>Client ID</strong> та <strong>Client Secret</strong>. Запишіть свій <strong>vanity-домен</strong> (частина перед <code>.zslogin.net</code>).</li>
        <li>У ZIA створіть (або виберіть) <strong>спеціальну категорію URL</strong>, до якої будуть додаватися заблоковані домени, та запишіть її точну назву.</li>
        <li>На картці <strong>Zscaler Connection</strong> платформи встановіть прапорець <span class="field-label">Enable Zscaler URL-Category blocking on Deny</span>.</li>
        <li>Заповніть <span class="field-label">API URL</span> (за замовчуванням <code>https://api.zsapi.net</code>), <span class="field-label">ZIdentity Vanity Domain</span>, <span class="field-label">Client ID</span>, <span class="field-label">Client Secret</span> та назву <span class="field-label">URL Category</span>.</li>
        <li>Натисніть <span class="btn-label">Save Configuration</span>, потім <span class="btn-label">Test Connection</span>, щоб підтвердити, що облікові дані працюють.</li>
    </ol>
    <figure class="doc-figure">
        <img src="app/docs/zscaler-card.png" alt="Zscaler Connection settings" loading="lazy">
