<div class="doc-section" id="admin-saml">
    <h2>SAML / SSO</h2>
    <p>Налаштуйте Single Sign-On за допомогою SAML 2.0. Перейдіть до <span class="menu-label">Admin</span> &rarr; <span class="menu-label">SAML</span>. Це дозволяє користувачам входити за допомогою провайдера ідентифікації вашої організації (Okta, Azure AD тощо).</p>
    <ol class="steps">
        <li>Встановіть прапорець <span class="field-label">Enable SAML 2.0</span>.</li>
        <li>Заповніть усі обов'язкові поля провайдера ідентифікації (<span class="field-label">IdP Entity ID</span>, <span class="field-label">IdP Single Sign-On URL</span>, <span class="field-label">IdP X.509 Certificate</span>) та постачальника послуг (<span class="field-label">SP Entity ID</span>, <span class="field-label">SP ACS URL</span>). SSO активується лише після заповнення <strong>усіх</strong> цих полів &mdash; частково заповнена форма залишається вимкненою.</li>
        <li>Натисніть <span class="btn-label">Save</span>.</li>
    </ol>

    <h3>Використання локального входу та SSO одночасно</h3>
    <p>За замовчуванням увімкнення SSO <strong>не</strong> вимикає локальну форму імені користувача/пароля &mdash; на сторінці входу відображається кнопка <strong>Sign in with SSO</strong> <em>та</em> локальний варіант входу, так що обидва працюють паралельно. Поведінка контролюється одним перемикачем локального входу:</p>
    <table>
        <tr><th>Режим</th><th>Що бачать користувачі</th></tr>
        <tr><td><strong>Local login enabled</strong> (за замовчуванням)</td><td>Кнопка SSO <em>та</em> форма імені користувача/пароля. Використовуйте це для роботи обох одночасно.</td></tr>
        <tr><td><strong>Local login disabled</strong> (тільки SSO)</td><td>SSO — єдиний шлях для звичайних користувачів. Призначений <strong>break-glass admin</strong> обліковий запис все одно може входити локально, тому несправний провайдер ідентифікації ніколи не заблокує всіх.</td></tr>
    </table>
    <p>Якщо SAML фактично не налаштований, перемикач ігнорується і локальний вхід завжди залишається доступним (захист від самоблокування).</p>

    <h3>Break-glass: дозвіл SAML та локального входу одночасно (конфігураційний файл) <span class="new-badge">Нове у 2.6.2</span></h3>
    <p>Перемикач локального входу можна встановити двома способами. Налаштування конфігураційного файлу, якщо воно присутнє, <strong>має пріоритет над значенням у базі даних</strong> &mdash; засіб break-glass, що не потребує доступу до бази даних, тому ви завжди можете відновити локальний вхід, навіть якщо SSO некоректно працює.</p>
    <table>
        <tr><th>Де</th><th>Як</th></tr>
        <tr><td>Admin &rarr; SAML page</td><td>На картці <strong>Connection Settings</strong> встановіть або зніміть прапорець <span class="field-label">Allow local username/password login (in addition to SSO)</span> та натисніть <span class="btn-label">Save SAML Configuration</span>. Це записує налаштування <code>local_login_enabled</code> (увімкнено за замовчуванням) &mdash; SQL не потрібен.</td></tr>
        <tr><td>Config file (має пріоритет якщо встановлено)</td><td>У <code>config/config.php</code>, в блоці <code>auth</code>, встановіть <code>'local_login_enabled' =&gt; true</code>, щоб локальний вхід завжди був доступний (обидва локальний + SSO), або <code>false</code> для лише SSO. Це <strong>перевизначає</strong> перемикач вище; поки встановлено, прапорець на сторінці SAML відображається як лише для читання. Видаліть рядок, щоб управляти ним знову через UI. Перезапустіть контейнер після редагування <code>config.php</code>.</td></tr>
    </table>
    <p>Для роботи <strong>обох SAML та локального входу</strong> без змін бази даних, налаштуйте SAML як зазначено вище та додайте наступне до блоку <code>auth</code> у <code>config/config.php</code>, потім перезапустіть контейнер:</p>
    <pre><code>'auth' =&gt; [
    // ...
    // Break-glass: true = local login always available alongside SSO;
    // false = SSO-only (break-glass admin can still log in locally).
    'local_login_enabled' =&gt; true,
],</code></pre>
</div>

<div class="doc-section" id="admin-ai">
    <h2>Інтеграція ШІ</h2>
    <p>Увімкніть функції на базі ШІ, включаючи вдосконалення нотаток оцінювання, пропозиції засобів контролю, коментарі щодо постачальників, аналіз ризиків FAIR за допомогою ШІ та мовну допомогу у звітах. Перейдіть до <span class="menu-label">Admin</span> &rarr; <span class="menu-label">AI Platform</span>, щоб вибрати провайдера та ввести його API-ключ. Одночасно активна лише одна платформа.</p>
    <p>Підтримувані платформи ШІ:</p>
    <ul>
        <li><strong>Anthropic (Claude)</strong> <span class="new-badge">Нове у 2.6.2</span> &mdash; підключається безпосередньо до нативного API Claude (наприклад <code>claude-opus-4-8</code>). Вставте свій API-ключ Anthropic; кінцева точка за замовчуванням — стандартна URL-адреса Messages. Підтримує живий <strong>веб-пошук</strong>, тому Breach Alerts та OSINT-скани ґрунтуються на актуальних, цитованих джерелах.</li>
        <li><strong>OpenAI (ChatGPT)</strong> <span class="new-badge">Нове у 2.6.2</span> &mdash; підключається безпосередньо до OpenAI (наприклад <code>gpt-4o</code>). Вставте свій API-ключ OpenAI. Для сканів Breach &amp; OSINT використовується модель із можливістю веб-пошуку (за замовчуванням <code>gpt-4o-search-preview</code>), тому ці скани ґрунтуються на живих джерелах.</li>
        <li><strong>OpenWebUI</strong> &mdash; JWT bearer token для кінцевої точки, сумісної з OpenAI.</li>
        <li><strong>LibreChat</strong> &mdash; автентифікація за API-ключем, на основі агента; агент управляє власною моделлю та вибіркою.</li>
        <li><strong>Custom</strong> &mdash; вставте шаблон заголовків + тіла у стилі curl для будь-якої іншої кінцевої точки, сумісної з OpenAI (або оркестратора).</li>
    </ul>
    <p><strong>Вибір та завантаження моделі:</strong> після введення та <strong>збереження</strong> ключа натисніть <span class="btn-label">Load Models</span> на картці цієї платформи, щоб отримати список доступних моделей (OpenWebUI / LibreChat / OpenAI). Для Anthropic введіть назву моделі безпосередньо (наприклад <code>claude-opus-4-8</code>).</p>
    <p><strong>Ґрунтування Breach Alerts:</strong> скани Breach &amp; OSINT потребують провайдера, який може здійснювати веб-пошук. <strong>Anthropic (Claude)</strong> та <strong>OpenAI (ChatGPT)</strong> обидва ґрунтуються нативно; OpenWebUI / LibreChat ґрунтуються лише якщо базовий агент має браузинг; Custom-платформа ґрунтується лише при налаштованій URL-адресі веб-пошуку.</p>
    <p>Активний провайдер ШІ також забезпечує <strong>автоматичний переклад питань оцінювання</strong> (дивіться <a href="#language">Зміна мови</a>).</p>
</div>

