                <li><span class="field-label">Test Frequency</span> &mdash; Як часто перевіряється цей засіб контролю (щодня, щотижня, щомісяця тощо)</li>
            </ul>
        </li>
        <li>У розділі <strong>Framework Mapping</strong> виберіть, які вимоги фреймворку задовольняє цей засіб контролю. Ви можете зіставити один засіб контролю з вимогами кількох фреймворків.</li>
