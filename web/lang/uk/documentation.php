<div class="doc-section" id="troubleshooting">
    <h2>Усунення неполадок</h2>

    <h3>Чому введення через закупівлі важливе (правило VID та Procurement Onboarding)</h3>
    <p>Це найпоширеніша причина, через яку постачальник не може рухатися вперед, тому варто розуміти. Платформа <strong>не дозволить подати постачальника на перевірку кіберпеки</strong>, доки на ньому не будуть записані два факти щодо закупівель:</p>
    <ul>
        <li><strong>Procurement Onboarding = Yes</strong> &mdash; підтвердження того, що постачальника встановлено та перевірено через процес закупівель вашої організації.</li>
        <li>Дійсний <strong>Vendor ID (VID)</strong> &mdash; 4&ndash;8-значне число, яке закупівлі присвоюють постачальнику.</li>
    </ul>
    <p>Навіщо це вимагати? Тому що VID — це спільний ключ, що пов'язує цього постачальника з записами закупівель, фінансів та контрактів. Якби команда кіберпеки перевірила та схвалила постачальника, якого відділ закупівель ніколи не вводив, ви б отримали дублювальних або «фантомних» постачальників, роботу з безпеки, яку не можна прив'язати до реального замовлення на купівлю, та звіти, що не збігаються. Вимога введення через закупівлі <em>спочатку</em> гарантує, що перевірка безпеки та запис закупівель вказують на одного й того самого, реального постачальника.</p>
    <div class="callout callout-warning">
        <strong>Виправлення:</strong> Відкрийте постачальника та на картці <strong>Vendor Information</strong> встановіть <strong>Procurement Onboarding</strong> на <strong>Yes</strong> та введіть 4&ndash;8-значний <strong>Vendor ID (VID)</strong> з вашої системи закупівель. Збережіть, потім натисніть <strong>Submit for Review</strong> ще раз. Якщо у вас ще немає VID, постачальник не завершив введення через закупівлі &mdash; почніть звідти.
    </div>

    <h3>Поширені проблеми та способи їх вирішення</h3>
    <table class="doc-table">
        <tr><th>Симптом</th><th>Ймовірна причина та виправлення</th></tr>
        <tr><td>«Cannot submit: Vendor must be onboarded at VSU before submission&hellip;»</td><td>Поле <strong>Procurement Onboarding</strong> не встановлено на <strong>Yes</strong>. Встановіть на Yes на картці Vendor Information та збережіть.</td></tr>
        <tr><td>«Cannot submit: A valid Vendor ID (VID) is required (4-8 digits)&hellip;»</td><td><strong>Vendor ID</strong> відсутній або не містить 4&ndash;8 цифр. Введіть дійсний VID від відділу закупівель.</td></tr>
        <tr><td>«Only draft requests can be submitted for review.»</td><td>Постачальник вже вийшов зі стану Draft. Подати можна лише запит, що досі знаходиться у статусі <strong>Draft</strong>.</td></tr>
        <tr><td>Кнопка <strong>Submit for Review</strong> не відображається</td><td>Вона з'являється лише для постачальників у статусі <strong>Draft</strong>, якщо у вас є дозвіл на редагування.</td></tr>
        <tr><td>«AI Review can only be forced for vendors whose services use AI.»</td><td>Встановіть <strong>Services Use AI</strong> на <strong>Yes</strong> для постачальника перед примусовим переходом до AI Review.</td></tr>
        <tr><td>Я не бачу модуль GRC на бічній панелі</td><td>Вам потрібно бути у групі <strong>Administrator</strong>, <strong>Cyber GRC</strong> або <strong>Auditor</strong>. Зверніться до адміністратора.</td></tr>
        <tr><td>Зміна мови не збереглася</td><td>Переконайтеся, що ви натиснули <strong>Update Language</strong> (а не просто змінили спадний список), і що мова увімкнена вашим адміністратором.</td></tr>
        <tr><td>«Test Connection» для Grip не вдалося</td><td>Перевірте, що базова URL-адреса закінчується на <code>/public/saas</code> та що API-токен дійсний та актуальний.</td></tr>
        <tr><td>Заборона додатка Shadow SaaS не заблокувала його в Zscaler</td><td>Блокування Zscaler повинно бути увімкнено та налаштовано, і вказана <strong>URL Category</strong> повинна вже існувати в Zscaler.</td></tr>
        <tr><td>Відділ закупівель не отримав дайджест електронної пошти</td><td>Переконайтеся, що дайджест увімкнено з одержувачами у розділі <strong>Admin &rarr; Email Settings</strong>, та що налаштування SMTP у <strong>Admin &rarr; Email</strong> правильні.</td></tr>
        <tr><td>Кнопка Upgrade повідомляє «Could not fetch manifest»</td><td>Проблема з реєстром/мережею при доступі до реєстру образів. Перевірте <strong>Registry Hostname</strong> у розділі <strong>Admin &rarr; Version</strong> та що хост може до нього дістатися.</td></tr>
    </table>
    <div class="callout callout-info">
        <strong>Все ще застрягли?</strong> Запишіть точне повідомлення на екрані та на якій сторінці ви були, потім зверніться до адміністратора платформи. Адміністратори можуть переглянути <strong>Admin &rarr; Activity Log</strong> для деталей.
    </div>
