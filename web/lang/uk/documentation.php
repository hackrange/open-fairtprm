        <li>Натисніть <span class="btn-label">+ New Control</span>.</li>
        <li>Заповніть поля:
            <ul>
                <li><span class="field-label">Control Title</span> &mdash; Коротка назва (наприклад, «MFA для всіх облікових записів користувачів»)</li>
                <li><span class="field-label">Description</span> &mdash; Детальний опис того, що робить цей засіб контролю</li>
                <li><span class="field-label">Control Type</span> &mdash; Preventive (превентивний), Detective (виявляючий), Corrective (коригуючий) або Directive (директивний)</li>
