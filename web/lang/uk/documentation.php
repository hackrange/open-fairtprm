<div class="doc-section" id="grc-gaps">
    <h2>Аналіз прогалин</h2>
    <p>Сторінка <strong>Gap Analysis</strong> збирає кожну слабкість, виявлену під час оцінювання &mdash; кожне питання, на яке відповіли <strong>Non-Conforming</strong> або <strong>Partial</strong> &mdash; в один пріоритизований список задач. Вона відповідає на питання «де ми не відповідаємо вимогам, і на що впливає кожна невідповідність?»</p>

    <h3>Як отримати доступ</h3>
    <ol class="steps">
        <li>Перейдіть до <span class="menu-label">GRC Module</span> &rarr; <span class="menu-label">Assessment &amp; Audit</span> &rarr; <span class="menu-label">Gaps</span>.</li>
        <li>Виберіть оцінювання, яке хочете проаналізувати, зі спадного списку <span class="field-label">Assessment</span>.</li>
    </ol>

    <h3>Що показує сторінка</h3>
    <p>Чотири зведені плитки у верхній частині підраховують <strong>Total Gaps</strong>, <strong>Non-Conforming</strong>, <strong>Partial</strong> та прогалини <strong>With Linked Risk</strong>. Нижче кожна прогалина відображається як рядок із:</p>
    <ul>
        <li><strong>Severity</strong> &mdash; значок: <em>Non-Conforming</em> (червоний) або <em>Partial</em> (бурштиновий).</li>
        <li><strong>Domain</strong> та <strong>Ref</strong> &mdash; домен безпеки та точне посилання на питання (наприклад, <code>GOV-08</code>).</li>
        <li><strong>Finding</strong> &mdash; текст питання, що описує, чого не вистачає.</li>
        <li><strong>Framework Impact</strong> &mdash; значки для кожної вимоги фреймворку, на яку впливає ця прогалина, щоб ви могли з першого погляду побачити, чи одне виправлення покращить SOC 2, ISO 27001, PCI DSS та інші одночасно.</li>
        <li><strong>Risk</strong> &mdash; чи зареєстровано ризик для цієї прогалини, та дія <span class="btn-label">View</span>, щоб відкрити повні деталі.</li>
    </ul>
    <figure class="doc-figure">
        <img src="app/docs/grc-gaps.png" alt="Gap Analysis page listing non-conforming and partial findings" loading="lazy">
        <figcaption><strong>GRC Module &rarr; Gaps.</strong> Кожна невідповідна або часткова відповідь стає прогалиною. Стовпець <strong>Framework Impact</strong> показує, які вимоги по кожному фреймворку торкається прогалина &mdash; закриття однієї прогалини може покращити кілька фреймворків одночасно.</figcaption>
    </figure>
</div>


