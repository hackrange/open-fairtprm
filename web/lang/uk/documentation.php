    <h2>Крок 5: Генерування звіту про відповідність фреймворку</h2>
    <p>Після відповідей на питання ви можете згенерувати детальний звіт про відповідність для будь-якого фреймворку. Цей звіт підходить для передачі аудиторам, регуляторам або керівництву.</p>

    <h3>Як згенерувати звіт</h3>
    <ol class="steps">
        <li>Перейдіть до <span class="menu-label">GRC Module</span> &rarr; <span class="menu-label">Compliance</span> &rarr; <span class="menu-label">Frameworks</span>.</li>
        <li>Виберіть оцінювання зі спадного списку <span class="field-label">Assessment</span> у верхній частині.</li>
        <li>Натисніть на картку фреймворку, за яким хочете звітувати (наприклад, «SOC2 &mdash; SOC 2 Type II»).</li>
        <li>Відкривається сторінка <strong>Framework Compliance Report</strong>, яка показує:
            <ul>
                <li><strong>Заголовок звіту</strong> &mdash; Назва фреймворку, назва оцінювання, тип, статус, обсяг, провідний аудитор, дати та загальний відсоток відповідності</li>
                <li><strong>Зведена статистика</strong> &mdash; Картки, що натискаються, що показують загальну кількість вимог, Conforming, Partial, Non-Conforming, Not Assessed та N/A</li>
                <li><strong>Картки вимог</strong> &mdash; По одній картці на кожну вимогу фреймворку, що показує посилання на вимогу, назву, значок статусу та всі зіставлені питання з відповідями</li>
            </ul>
        </li>
        <li>Щоб <strong>фільтрувати вимоги за статусом</strong>, натисніть будь-яку зі зведених статистичних карток у верхній частині. Наприклад, натисніть <strong>Non-Conforming</strong>, щоб показати лише невідповідні вимоги. Натисніть ще раз (або натисніть «Total Requirements»), щоб показати всі.</li>
        <li>Щоб <strong>роздрукувати звіт</strong>, натисніть кнопку <span class="btn-label">Print Report</span> у верхній частині. Відкриється діалогове вікно друку браузера. Ви можете роздрукувати на папері або вибрати «Зберегти як PDF», щоб створити PDF-файл.</li>
    </ol>

    <h3>Що показує кожна картка вимог</h3>
    <p>Для кожної вимоги у звіті ви побачите:</p>
    <ul>
        <li><strong>Посилання на вимогу</strong> &mdash; Офіційний довідковий номер (наприклад, «CC6.1» для SOC 2)</li>
        <li><strong>Назва вимоги</strong> &mdash; Що говорить вимога</li>
        <li><strong>Значок статусу</strong> &mdash; Кольоровий код: зелений (Conforming), бурштиновий (Partial), червоний (Non-Conforming), сірий (Not Assessed / N/A)</li>
        <li><strong>Зіставлені питання</strong> &mdash; Кожне питання, що відповідає цій вимозі, яке показує:
            <ul>
                <li>Посилання на питання та текст</li>
                <li>Рейтинг зрілості (1-4) з візуальною шкалою</li>
                <li>Статус відповідності</li>
                <li>Статус перевірки (Pending, Validated, Rejected, Needs Review)</li>
                <li>Ім'я оцінювача та дата</li>
                <li>Сила зіставлення (Exact, Strong, Partial, Related)</li>
                <li>Нотатки оцінювача</li>
                <li>Нотатки перевірки</li>
