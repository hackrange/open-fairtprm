<div class="doc-section" id="grc-overview">
    <h2>Модуль GRC: що таке Governance, Risk &amp; Compliance?</h2>
    <p><strong>GRC</strong> означає <strong>Governance, Risk, and Compliance</strong> (Корпоративне управління, ризики та відповідність). Це практика забезпечення того, що ваша організація відповідає регуляторним вимогам, дотримується найкращих практик безпеки, управляє ризиками та може довести відповідність аудиторам і регуляторам.</p>

    <p>Модуль GRC допомагає вам:</p>
    <ul>
        <li><strong>Оцінити зрілість безпеки</strong> за допомогою єдиного уніфікованого опитувальника, який одночасно відображається на кілька фреймворків відповідності</li>
        <li><strong>Відстежувати відповідність</strong> стандартам SOC 2, ISO 27001, PCI DSS, NIST CSF, CMMC, HIPAA, CIS Controls та іншим</li>
        <li><strong>Управляти внутрішніми засобами контролю</strong> &mdash; документувати заходи безпеки, впроваджені вашою організацією</li>
        <li><strong>Збирати та зберігати докази</strong> &mdash; завантажувати знімки екрана, експорти конфігурацій, документи щодо політик та сертифікати, що підтверджують відповідність</li>
        <li><strong>Управляти політиками</strong> &mdash; створювати, версіонувати, затверджувати та публікувати організаційні політики безпеки</li>
        <li><strong>Проводити аудити</strong> &mdash; планувати аудити, реєструвати висновки, призначати усунення порушень та відстежувати їх закриття</li>
        <li><strong>Відстежувати ризики</strong> &mdash; вести реєстр ризиків з оцінкою ймовірності/впливу та планами обробки</li>
        <li><strong>Моніторити безперервно</strong> &mdash; налаштовувати автоматизовані перевірки, що верифікують засоби контролю відповідності за розкладом</li>
    </ul>

    <div class="callout callout-warning">
        <strong>Важлива концепція &mdash; Уніфіковані питання:</strong> Платформа містить <strong>146 уніфікованих питань безпеки</strong>, організованих у <strong>14 доменів безпеки</strong> (Governance, Identity &amp; Access Management, Data Security, Network Security тощо). Кожне питання попередньо зіставлено з конкретними вимогами у кількох фреймворках відповідності. Коли ви відповідаєте на питання один раз, відповідь автоматично застосовується до кожного фреймворку, з яким зіставлено це питання. Це усуває необхідність відповідати на одне й те саме питання окремо для SOC 2, ISO 27001 та PCI DSS.
    </div>
