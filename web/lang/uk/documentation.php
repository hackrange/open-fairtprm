<div class="doc-section" id="ai-review">
    <h2>AI Review для постачальників <span class="new-badge">Нове у 2.6.2</span></h2>
    <p>Деякі постачальники надають послуги, що використовують штучний інтелект. Такі постачальники можуть нести різні ризики, тому у v2.6.2 додано спеціальний статус <strong>AI Review</strong> для їх окремого відстеження в процесі перевірки.</p>

    <h3>Як постачальник потрапляє до AI Review</h3>
    <p>На картці <strong>Vendor Information</strong> є поле <span class="field-label">Services Use AI</span>. Коли воно встановлено на <strong>Yes</strong>, авторизований перевіряючий (користувач <strong>Cyber TPRM</strong> або <strong>Administrator</strong>, у режимі редагування постачальника) бачить посилання <span class="btn-label">Force AI Review</span> безпосередньо під цим полем.</p>
    <ol class="steps">
        <li>Відкрийте постачальника та підтвердіть, що <span class="field-label">Services Use AI</span> встановлено на <strong>Yes</strong>.</li>
        <li>Натисніть <span class="btn-label">Force AI Review</span>. Підтвердіть підказку: <em>«Force this vendor into AI Review?»</em></li>
        <li>Статус постачальника змінюється на <strong>AI Review</strong>.</li>
    </ol>
    <div class="callout callout-info">
        <strong>Чому посилання може не з'являтися?</strong> Посилання <strong>Force AI Review</strong> відображається лише коли (1) у вас є дозвіл на затвердження, (2) ви перебуваєте в режимі редагування, (3) <strong>Services Use AI</strong> має значення <strong>Yes</strong>, і (4) постачальник ще не перебуває в AI Review. Якщо <strong>Services Use AI</strong> — «No», ви побачите повідомлення <em>«AI Review can only be forced for vendors whose services use AI.»</em></p>
    </div>
    <p>На сторінці <a href="#procurement-cyber-status">Procurement Cyber Status</a> та у фільтрі <strong>Review</strong> списку постачальників постачальники зі статусами <strong>In Review</strong> та <strong>AI Review</strong> відображаються разом &mdash; тому жоден постачальник на перевірці ніколи не прихований лише через те, що він перевіряється за допомогою ШІ.</p>
