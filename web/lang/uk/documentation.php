    <h2>Крок 4: Перегляд балів відповідності</h2>
    <p>Коли ви відповідаєте на питання, платформа розраховує відсоток відповідності для кожного фреймворку в режимі реального часу.</p>

    <h3>Перегляд балів на сторінці Frameworks</h3>
    <ol class="steps">
        <li>Перейдіть до <span class="menu-label">GRC Module</span> &rarr; <span class="menu-label">Compliance</span> &rarr; <span class="menu-label">Frameworks</span>.</li>
        <li>У верхній частині сторінки ви побачите спадний список <span class="field-label">Assessment</span>. Виберіть оцінювання, для якого хочете переглянути бали. За замовчуванням вибрано найновіше оцінювання.</li>
        <li>Нижче спадного списку ви побачите картки фреймворків &mdash; по одній для кожного фреймворку відповідності, до якого зіставлені питання. Кожна картка показує:
            <ul>
                <li><strong>Кругову діаграму</strong> із загальним відсотком відповідності (наприклад, 75%)</li>
