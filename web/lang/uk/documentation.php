                <li><span class="field-label">Implementation Status</span> &mdash; Planned (запланований), In Progress (у процесі), Implemented (впроваджений) або Not Applicable (не застосовно)</li>
                <li><span class="field-label">Effectiveness</span> &mdash; Not Tested (не перевірений), Ineffective (неефективний), Partially Effective (частково ефективний) або Effective (ефективний)</li>
