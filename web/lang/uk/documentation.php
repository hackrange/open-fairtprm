        <details class="faq-item"><summary>Що робить інтеграція Zscaler?<span class="faq-tag">Integrations</span></summary>
            <div class="faq-body"><p>Коли ви <strong>Deny</strong> (забороняєте) несанкціонований додаток, платформа може додати його веб-домен до категорії URL блокування у вашому обліковому записі Zscaler, щоб люди не могли до нього дістатися. Натискання <strong>Allow</strong> пізніше знімає блокування. Дивіться <a href="#zscaler">Інтеграція блокування Zscaler</a>.</p></div></details>

        <details class="faq-item"><summary>В чому різниця між Allow, Deny та Dismiss для додатка Shadow SaaS?<span class="faq-tag">Integrations</span></summary>
            <div class="faq-body"><p><strong>Allow</strong> починає введення додатка як постачальника; <strong>Deny</strong> позначає його несанкціонованим (та може заблокувати в Zscaler); <strong>Dismiss</strong> приховує його зі списку. Відхилені додатки залишаються відхиленими навіть після наступних синхронізацій.</p></div></details>

        <details class="faq-item"><summary>Хто може бачити модуль GRC?<span class="faq-tag">Access</span></summary>
            <div class="faq-body"><p>Користувачі у групах <strong>Administrator</strong>, <strong>Cyber GRC</strong> або <strong>Auditor</strong>. Якщо ви його не бачите, попросіть адміністратора додати вас до однієї з цих груп. Дивіться <a href="#roles">Ролі та дозволи користувачів</a>.</p></div></details>

        <details class="faq-item"><summary>Як увімкнути двофакторну автентифікацію (2FA)?<span class="faq-tag">Account</span></summary>
            <div class="faq-body"><p>Відкрийте <strong>Profile</strong> та використовуйте картку <strong>Two-Factor Authentication (TOTP)</strong>, щоб увімкнути її за допомогою додатка автентифікатора, такого як Google Authenticator або Microsoft Authenticator.</p></div></details>

        <details class="faq-item"><summary>Чи можна зберегти або роздрукувати цю документацію?<span class="faq-tag">General</span></summary>
