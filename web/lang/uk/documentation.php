<div class="doc-section" id="question-types">
    <h2>Типи питань «Телефон» та «ПДВ» <span class="new-badge">Нове у 2.6.2</span></h2>
    <p><strong>Template Builder</strong> (<span class="menu-label">Admin</span> &rarr; <span class="menu-label">Assessment Templates</span>) отримує два нових типи питань, які фіксують контактні та податкові дані у чіткому, стандартному форматі. Їх можна використовувати в будь-якому шаблоні оцінювання або введення, і, як і інші питання, їх можна зіставити з полем постачальника, щоб відповідь потрапила до запису постачальника.</p>

    <h3>Телефон</h3>
    <p>Тип <strong>Phone</strong> показує вибір країни з прапором та кодом набору поруч із полем номера. США відображаються першими; всі інші країни йдуть в алфавітному порядку. Незалежно від формату, який вводить людина &mdash; <code>314-444-5544</code>, <code>(314)&nbsp;444-5544</code> або <code>3144445544</code> &mdash; номер зберігається в єдиному стандартному міжнародному форматі (наприклад, вибір прапора США та введення <code>3144445544</code> зберігає <code>+13144445544</code>). Стандартна форма запиту на введення постачальника тепер використовує цей тип для номера телефону основного контакту, а також поле телефону у <strong>attestation</strong> оцінювання.</p>

    <h3>ПДВ (номер ПДВ ЄС)</h3>
    <p>Тип <strong>VAT</strong> призначений для номерів ПДВ ЄС. Для захисту від помилок друку його потрібно <strong>ввести двічі</strong>, і два введення повинні збігатися перед збереженням. Номер зберігається у стандартному вигляді (верхній регістр, без пробілів або розділових знаків &mdash; наприклад <code>DE123456789</code>).</p>
    <ul>
        <li><strong>Безкоштовна жива перевірка.</strong> Коли ви завершуєте введення, платформа перевіряє номер через офіційну службу <strong>EU VIES</strong> (Система обміну інформацією про ПДВ Європейської Комісії). VIES безкоштовна, не потребує облікового запису та відображає дані з живих реєстрів кожної країни-члена.</li>
        <li><strong>Рекомендаційна, ніколи не блокуюча.</strong> Якщо VIES не може підтвердити номер, він все одно зберігається &mdash; просто з'являється повідомлення з проханням перевірити його ще раз. Якщо VIES тимчасово повільна або реєстр певної країни тимчасово недоступний, номер зберігається і вам пропонують перевірити його пізніше.</li>
        <li><strong>Деталі на запит.</strong> Коли VIES підтверджує номер, поруч з ним з'являється кнопка інформації (&#9432;). Натискання на неї відкриває панель із зареєстрованою назвою та адресою компанії, отриманими від VIES.</li>
    </ul>
    <div class="callout callout-info">
        <strong>Зіставлення ПДВ із записом постачальника.</strong> Спеціальне поле <code>vat_number</code> доступне, тому питання про ПДВ, зіставлене з ним, зберігає значення в запису постачальника. Коли ви вибираєте тип питання VAT у Template Builder, це зіставлення вибирається автоматично.
    </div>

    <h3>ПДВ на сторінці постачальника</h3>
    <p>Номер ПДВ постачальника відображається у картці <strong>Vendor Information</strong> на сторінці введення постачальника. Якщо ПДВ не зареєстровано, з'являється кнопка <strong>&ldquo;+ Add VAT&rdquo;</strong>, яка відразу переходить у режим редагування з фокусом на полі ПДВ.</p>

    <h3>Пошук постачальників за номером ПДВ</h3>
    <p>Поле <strong>швидкого пошуку</strong> у верхньому правому куті платформи тепер також шукає збіги за номером ПДВ, поряд із назвою постачальника, доменом та зацікавленою стороною. Прямі збіги за власною назвою постачальника, доменом або номером ПДВ завжди відображаються першими.</p>

    <h2>Банер оцінювання Procurement Onboarding <span class="new-badge">Нове у 2.6.2</span></h2>
    <p>Коли статус <strong>Procurement Onboarding</strong> постачальника встановлений на <strong>No</strong>, банер тепер чітко вказує, що <em>автоматизоване оцінювання постачальника вимкнено до завершення Procurement Onboarding</em>. Він з'являється як на сторінці введення постачальника, так і під відповідним питанням оцінювання, та миттєво оновлюється зі зміною відповіді.</p>

    <h2>Подання оцінювання: перевірка обов'язкових полів <span class="new-badge">Нове у 2.6.2</span></h2>
