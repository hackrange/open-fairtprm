                    <h2>Вступ</h2>

                    <h3>Мета</h3>
                    <p>Цей документ містить вичерпну документацію для платформи Fair TPRM &amp; GRC. Він слугує як посібником користувача, так і довідковим посібником для всіх співробітників, задіяних у управлінні ризиками третіх сторін, корпоративному управлінні, оцінюванні ризиків та забезпеченні відповідності.</p>
                    <p>Цільова аудиторія включає аналітиків GRC, офіцерів з відповідності, аудиторів, персонал з ІТ-безпеки, команди із закупівель та системних адміністраторів. Незалежно від того, чи проводите ви своє перше оцінювання відповідності, чи управляєте поточною програмою аудиту, цей посібник надає покрокові інструкції, які вам потрібні.</p>

                    <h3>Охоплення</h3>
                    <p>Ця документація охоплює такі модулі та можливості платформи:</p>
                    <ul>
                        <li><strong>Модуль GRC</strong> &mdash; Уніфіковані оцінювання відповідності за кількома фреймворками (SOC 2, ISO 27001, PCI DSS, NIST CSF, CMMC, HIPAA, CIS Controls, NIST 800-171), управління внутрішніми засобами контролю, збір доказів, управління життєвим циклом політик, управління аудитами, реєстр ризиків, безперервний моніторинг та оцінювання зрілості</li>
                        <li><strong>Модуль TPRM</strong> &mdash; Введення сторонніх постачальників, класифікація ризиків, оцінювання безпеки, кількісний аналіз ризиків (FAIR), зовнішнє оцінювання безпеки, відстеження ризиків четвертих сторін та виявлення тіньових SaaS</li>
                        <li><strong>Адміністративний портал</strong> &mdash; Конфігурація системи, управління користувачами та групами, брендинг, налаштування електронної пошти, інтеграція SSO/SAML та конфігурація платформи штучного інтелекту</li>
                    </ul>

                    <h3>Як користуватися цим посібником</h3>
                    <p>Цей посібник організований у чотири частини. <strong>Частина 1 (Початок роботи)</strong> охоплює навігацію по платформі, ролі користувачів та перший вхід. <strong>Частина 2 (Модуль GRC)</strong> надає детальний покроковий огляд процесу оцінювання відповідності, починаючи зі створення першого оцінювання та переходячи до збору доказів, підрахунку балів та генерації звітів. <strong>Частина 3 (Модуль TPRM)</strong> охоплює управління ризиками постачальників. <strong>Частина 4 (Адміністративний портал)</strong> охоплює системне адміністрування.</p>
                    <p>Якщо ви вперше використовуєте платформу, почніть з розділу <em>Початок роботи</em>, а потім дотримуйтесь п'ятикрокового посібника швидкого старту GRC. Кожен крок містить точні інструкції з вказівкою на кожне натискання.</p>

                    <h3>Умовні позначення документа</h3>
