    <h2>Крок 3: Завантаження доказів</h2>
    <p>Докази підтверджують точність ваших відповідей. Аудитори очікуватимуть бачити докази для кожної заяви про відповідність. Докази можуть включати знімки екрана, експорти конфігурацій, документи щодо політик, журнали аудиту, сертифікати тощо.</p>

    <h3>Як завантажити докази під час оцінювання</h3>
    <ol class="steps">
        <li>Відповідаючи на питання в <span class="menu-label">Assessment Questionnaire</span>, знайдіть розділ <strong>Evidence</strong> під областю відповіді на питання.</li>
        <li>Натисніть <span class="btn-label">Upload Evidence</span> або значок вкладення.</li>
        <li>Виберіть файл зі свого комп'ютера. Підтримувані типи включають PDF, зображення (PNG, JPG), документи Word, таблиці Excel та текстові файли.</li>
        <li>Дайте доказу описову <span class="field-label">Title</span> (наприклад, «Знімок екрана конфігурації MFA — консоль адміністратора Okta»).</li>
        <li>Доказ автоматично прив'язується до поточного питання оцінювання.</li>
        <li>Ви можете завантажити кілька файлів доказів на одне питання.</li>
    </ol>

    <div class="callout callout-success">
        <strong>Безпека:</strong> Усі завантажені файли доказів шифруються (AES-256-CBC) перед збереженням у базі даних. Коли ви завантажуєте докази, вони розшифровуються на льоту. Це забезпечує захист конфіденційних документів про відповідність у стані спокою.
    </div>

    <h3>Бібліотека доказів</h3>
    <p>Ви також можете управляти доказами окремо через <span class="menu-label">GRC Module</span> &rarr; <span class="menu-label">Evidence &amp; Monitoring</span> &rarr; <span class="menu-label">Evidence Library</span>. Ця сторінка показує всі докази по всіх оцінюваннях і засобах контролю, з фільтрацією за типом, статусом та датою закінчення терміну дії.</p>
